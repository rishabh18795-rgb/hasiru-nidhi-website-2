// Builds supabase/setup-all.sql: every migration, in order, as ONE file you can paste into the Supabase SQL editor.
// Usage: npm run db:bundle   (a test fails if the committed bundle is out of date)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "supabase/migrations");

export function buildBundle() {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
  const parts = files.map((f) => `-- ======================================================================\n-- ${f}\n-- ======================================================================\n${fs.readFileSync(path.join(dir, f), "utf8").trimEnd()}\n`);
  return `-- Hasiru Nidhi marketplace: complete database setup (all migrations in order).\n-- Generated by \`npm run db:bundle\` — do not edit by hand.\n-- Run once on a NEW Supabase project (SQL Editor > New query > paste > Run).\n-- It is not safe to run twice; to change an existing database, run only the newest migration files.\n\n${parts.join("\n")}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, "supabase/setup-all.sql"), buildBundle());
  console.log("wrote supabase/setup-all.sql");
}
