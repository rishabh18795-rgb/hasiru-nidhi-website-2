// Builds supabase/seed.sql from supabase/demo-properties.json (the single source for the six demonstration listings).
// Usage: npm run db:seed   (a test fails if the committed seed.sql is out of date)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

export function buildSeed() {
  const data = JSON.parse(fs.readFileSync(path.join(root, "supabase/demo-properties.json"), "utf8"));
  const props = data.properties;
  const out = [];
  out.push(`-- DEMONSTRATION DATA ONLY — generated by scripts/gen-seed.mjs from supabase/demo-properties.json. Do not edit by hand.
--
-- Six FICTIONAL listings for testing the marketplace interface, search filters, detail pages and the booking flow.
-- Every row is flagged is_sample = true: the site shows a "DEMO LISTING — SAMPLE DATA" badge, keeps them out of Google
-- (noindex, not in the sitemap) and the descriptions say so. They are NOT real properties, owners, prices or reviews, and the
-- photographs are illustrative. They have no host (platform-managed) until you assign them to YOUR OWN test host account with
-- supabase/scripts/assign_demo_listings_to_host.sql so you can test the host side of the booking flow.
--
-- Run AFTER all migrations. Safe to run twice (existing slugs are skipped).
-- Remove everything again with supabase/scripts/remove_sample_data.sql.
`);
  out.push(`insert into public.properties
  (slug, name, category_id, summary, description, city, state, region, rooms_count, max_guests, bedrooms, beds, bathrooms,
   accommodation_arrangement, price_inr, price_unit, weekend_price_inr, included_guests, extra_guest_fee_inr, cleaning_fee_inr,
   tax_percent, min_nights, max_nights, check_in_time, check_out_time, house_rules, cancellation_policy,
   status, is_featured, is_sample, terms_accepted_at, photo_rights_confirmed_at, submitted_at, published_at)
values`);
  out.push(props.map((p) => `  (${[
    q(p.slug), q(p.name), `(select id from public.property_categories where slug = ${q(p.category)})`, q(p.summary), q(p.description),
    q(p.city), q(p.state), q(p.region), p.rooms, p.max_guests, p.bedrooms, p.beds, p.bathrooms, q(p.arrangement), p.price_inr, q(p.price_unit),
    q(p.weekend_price_inr ?? null), q(p.included_guests ?? null), q(p.extra_guest_fee_inr ?? null), q(p.cleaning_fee_inr ?? null),
    p.tax_percent ?? 0, p.min_nights, p.max_nights, q(p.check_in), q(p.check_out), q(p.house_rules), q(p.cancellation_policy),
    "'approved'", p.featured ? "true" : "false", "true", "now()", "now()", "now()", "now()",
  ].join(", ")})`).join(",\n") + "\non conflict (slug) do nothing;\n");

  out.push(`insert into public.property_images (property_id, path, source, alt, sort_order)
select p.id, v.path, 'static', v.alt, v.ord
  from (values
${props.flatMap((p) => p.images.map((im, i) => `    (${q(p.slug)}, ${q(im.path)}, ${q(im.alt)}, ${i})`)).join(",\n")}
  ) as v(slug, path, alt, ord)
  join public.properties p on p.slug = v.slug
 where not exists (select 1 from public.property_images i where i.property_id = p.id and i.path = v.path);
`);
  out.push(`insert into public.property_amenities (property_id, amenity_id)
select p.id, a.id
  from (values
${props.flatMap((p) => p.amenities.map((a) => `    (${q(p.slug)}, ${q(a)})`)).join(",\n")}
  ) as v(slug, amenity)
  join public.properties p on p.slug = v.slug
  join public.amenities a on a.slug = v.amenity
on conflict do nothing;
`);
  out.push(`insert into public.property_experiences (property_id, experience_id)
select p.id, e.id
  from (values
${props.flatMap((p) => p.experiences.map((e) => `    (${q(p.slug)}, ${q(e)})`)).join(",\n")}
  ) as v(slug, experience)
  join public.properties p on p.slug = v.slug
  join public.experiences e on e.slug = v.experience
on conflict do nothing;
`);
  const blocks = props.flatMap((p) => p.blocks.map((b) => `    (${q(p.slug)}, ${b.from_days}, ${b.to_days}, ${q(b.reason)})`));
  if (blocks.length) {
    out.push(`-- Demo blocked ranges (relative to today) so the availability calendar has something to show.
insert into public.availability_blocks (property_id, start_date, end_date, reason)
select p.id, current_date + v.from_days, current_date + v.to_days, v.reason
  from (values
${blocks.join(",\n")}
  ) as v(slug, from_days, to_days, reason)
  join public.properties p on p.slug = v.slug
 where not exists (select 1 from public.availability_blocks b where b.property_id = p.id and b.reason = v.reason);
`);
  }
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, "supabase/seed.sql"), buildSeed());
  console.log("wrote supabase/seed.sql");
}
