import fs from "node:fs";
import path from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { btree_gist } from "@electric-sql/pglite/contrib/btree_gist";
import { describe, expect, it } from "vitest";

/**
 * Recovery procedure for the marketplace migrations (M1 to M7), generated from a REAL before/after catalog diff and then executed:
 *   supabase/rollback/marketplace-rollback.sql removes everything the marketplace added and restores the one existing function it extended.
 * Use it ONLY if no genuine marketplace data exists yet; otherwise restore from the backup taken before the rollout (see docs/LAUNCH_CHECKLIST.md).
 * Run `UPDATE_ROLLBACK=1 npx vitest run tests/db/rollback.test.ts` after adding a migration to regenerate the file.
 */
const ROOT = path.resolve(__dirname, "../..");
const DIR = path.join(ROOT, "supabase/migrations");
const FILE = path.join(ROOT, "supabase/rollback/marketplace-rollback.sql");
const BASELINE_BEFORE = "20261120";

async function boot(filter: (f: string) => boolean): Promise<PGlite> {
  const db = new PGlite({ extensions: { btree_gist } });
  await db.exec(`
    create role anon nologin; create role authenticated nologin; create role service_role nologin bypassrls;
    create schema auth;
    create table auth.users (id uuid primary key default gen_random_uuid(), email text, raw_user_meta_data jsonb not null default '{}'::jsonb, email_confirmed_at timestamptz);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    grant usage on schema public to anon, authenticated, service_role; grant usage on schema auth to anon, authenticated, service_role;
    alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
    alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
    alter default privileges in schema public grant all on functions to anon, authenticated, service_role;`);
  for (const f of fs.readdirSync(DIR).filter((x) => x.endsWith(".sql") && filter(x)).sort()) await db.exec(fs.readFileSync(path.join(DIR, f), "utf8"));
  return db;
}

async function snapshot(db: PGlite) {
  const list = async (sql: string) => (await db.query<{ v: string }>(sql)).rows.map((r) => r.v).sort();
  return {
    tables: await list(`select c.relname as v from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('r', 'p')`),
    functions: await list(`select p.oid::regprocedure::text as v from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.prokind = 'f'`),
    types: await list(`select t.typname as v from pg_type t join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' and t.typtype = 'e'`),
    policies: await list(`select tablename || '.' || policyname as v from pg_policies where schemaname = 'public'`),
    triggers: await list(`select tgrelid::regclass::text || '.' || tgname as v from pg_trigger where not tgisinternal and tgrelid::regclass::text not like 'auth.%'`),
    settings: await list(`select key as v from public.platform_settings`),
    validate: await list(`select md5(pg_get_functiondef('public.platform_settings_validate()'::regprocedure)) as v`),
  };
}

async function generate(): Promise<string> {
  const base = await boot((f) => f < BASELINE_BEFORE);
  const full = await boot(() => true);
  const b = await snapshot(base), f = await snapshot(full);
  const added = <T,>(k: keyof typeof b) => (f[k] as T[]).filter((x) => !(b[k] as T[]).includes(x));
  const validateDef = (await base.query<{ d: string }>(`select pg_get_functiondef('public.platform_settings_validate()'::regprocedure) as d`)).rows[0].d;
  const storagePolicies = [...new Set(fs.readdirSync(DIR).filter((x) => x >= BASELINE_BEFORE).flatMap((x) => [...fs.readFileSync(path.join(DIR, x), "utf8").matchAll(/create policy "([^"]+)" on storage\.objects/g)].map((m) => m[1])))].sort();
  const lines = [
    "-- Hasiru Nidhi marketplace ROLLBACK (generated by tests/db/rollback.test.ts; do not edit by hand).",
    "-- Removes everything migrations 20261120 to 20261125 added and restores the one existing function they extended. It DELETES all marketplace data",
    "-- (vendors, products, services, orders, requests, reviews). Use it only before any genuine marketplace data exists; otherwise restore the pre-rollout backup.",
    "-- Stays, bookings, profiles, properties, gardening enquiries and payments are not touched. Storage files are not deleted (remove them in the Dashboard if wanted).",
    "begin;",
    ...added<string>("tables").map((t) => `drop table if exists public.${t} cascade;`),
    ...added<string>("functions").map((fn) => `drop function if exists ${fn} cascade;`),
    ...added<string>("types").map((t) => `drop type if exists public.${t} cascade;`),
    "delete from public.platform_settings where key like 'marketplace\\_%';",
    `${validateDef.trim()};`,
    "do $storage$ begin",
    "  if to_regclass('storage.objects') is not null then",
    ...storagePolicies.map((p) => `    execute 'drop policy if exists "${p}" on storage.objects';`),
    "  end if;",
    "end $storage$;",
    "commit;",
    "",
  ];
  return lines.join("\n");
}

describe("marketplace rollback", () => {
  it("is up to date with the migrations (regenerate with UPDATE_ROLLBACK=1)", async () => {
    const sql = await generate();
    if (process.env.UPDATE_ROLLBACK) fs.writeFileSync(FILE, sql);
    expect(fs.readFileSync(FILE, "utf8")).toBe(sql);
  }, 60_000);

  it("restores the pre-marketplace schema exactly: tables, functions, types, policies, triggers, settings and the settings validator", async () => {
    const before = await snapshot(await boot((f) => f < BASELINE_BEFORE));
    const db = await boot(() => true);
    expect((await snapshot(db)).tables.length).toBeGreaterThan(before.tables.length);
    await db.exec(fs.readFileSync(FILE, "utf8"));
    expect(await snapshot(db)).toEqual(before);
  }, 60_000);

  it("leaves the original Stay data model working: a stay can still be listed and booked after the rollback", async () => {
    const db = await boot(() => true);
    await db.exec(fs.readFileSync(FILE, "utf8"));
    const names = (await db.query<{ n: string }>("select relname as n from pg_class c join pg_namespace s on s.oid = c.relnamespace where s.nspname = 'public' and relkind = 'r'")).rows.map((r) => r.n);
    for (const t of ["profiles", "properties", "bookings", "payments", "gardening_enquiries"]) expect(names).toContain(t);
    for (const t of ["vendors", "products", "orders", "services", "service_requests", "marketplace_reviews"]) expect(names).not.toContain(t);
    const fns = (await db.query<{ n: string }>("select proname as n from pg_proc p join pg_namespace s on s.oid = p.pronamespace where s.nspname = 'public'")).rows.map((r) => r.n);
    for (const f of ["request_booking", "respond_to_booking", "cancel_booking", "search_properties"]) expect(fns).toContain(f);
  }, 60_000);
});
